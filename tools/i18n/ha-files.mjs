// make ha-files: the Home Assistant files (dashboard, scripts, blueprints) in every language, from their templates
// (docs/plans/i18n.md, I5). Each `*.tmpl.yaml` under home-assistant/ gives one file per language of LANGS:
//
//   {{t:key}}   the key's text from home-assistant/i18n-yaml/<lang>.json, as a YAML double-quoted scalar (JSON's
//               escaping), so no translation can break the YAML. It must be a whole value: `name: {{t:key}}`,
//               `- {{t:key}}`, or an item of a flow collection, never inside other text
//   {{lang}}    the language's code
//   {{file}}    the generated file's name (a blueprint's source_url)
//
// Anything else in double braces is Home Assistant's own Jinja and stays as it is. A generated file starts with a
// header naming its template and language (tools/ha-dashboard-check.py reads it to find each set's languages).
//
//   node tools/i18n/ha-files.mjs            write the files
//   node tools/i18n/ha-files.mjs --check    write nothing; fail when a file differs from what it would write, or a
//                                           template uses a key a dictionary lacks (make i18n-check, so CI)
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { isPlural } from "../../home-assistant/i18n.js";
import { LANGS, FALLBACK, SURFACES, loadSurface } from "./lib.mjs";

export const TEMPLATE = ".tmpl.yaml";
export const HEADER = "# Generated by make ha-files from";

/**
 * Generated files whose path is not <name>.<lang>.yaml. The French blueprint keeps the path it had before there
 * were languages: every copy imported since points its source_url there, and Home Assistant re-imports from it.
 */
export const KEPT_PATHS = {
  "home-assistant/blueprints/pool_fill_too_long.tmpl.yaml": { fr: "pool_fill_too_long.yaml" },
};

/** The file a template gives in `lang`, relative to the repo's root. */
export function outputPath(template, lang, kept = KEPT_PATHS) {
  const dir = path.posix.dirname(template);
  const name = kept[template]?.[lang] ?? `${path.posix.basename(template, TEMPLATE)}.${lang}.yaml`;
  return path.posix.join(dir, name);
}

/** Every template under `dir` (relative to root), sorted; dist/ and dot-folders left out. */
export function listTemplates(root, dir = "home-assistant") {
  const out = [];
  const walk = (rel) => {
    let entries = [];
    try { entries = readdirSync(path.join(root, rel), { withFileTypes: true }); } catch { return; }
    for (const e of entries.sort((a, b) => a.name.localeCompare(b.name))) {
      const child = path.posix.join(rel, e.name);
      if (e.isDirectory() && !e.name.startsWith(".") && e.name !== "dist" && e.name !== "node_modules") walk(child);
      else if (e.isFile() && e.name.endsWith(TEMPLATE)) out.push(child);
    }
  };
  walk(dir);
  return out;
}

const TOKEN = /\{\{\s*t:([\w.:-]+)\s*\}\}/g;
// What may stand before and after {{t:key}} so that it is a whole YAML value.
const BEFORE = /(?:^\s*|:\s+|^\s*(?:-\s+)+|[[{,]\s*)$/;
const AFTER = /^\s*(?:[,\]}].*|#.*)?$/;

/** The header line of a generated file. */
export const header = (template, lang, dictDir) =>
  `${HEADER} ${path.posix.basename(template)} (${lang}): edit that template or ${dictDir}/${lang}.json, then make ha-files. Never edit this file.`;

/**
 * A template's text in one language. `texts` is the language's flat dictionary (Map key → text). Returns
 * { text, errors }; `text` is null when a key couldn't be filled.
 */
export function render(source, { template, lang, file, texts, dictDir }) {
  const errors = [];
  const lines = source.split("\n").map((line, i) => line.replace(TOKEN, (m, key, at) => {
    const where = `${template}:${i + 1}`;
    if (!BEFORE.test(line.slice(0, at)) || !AFTER.test(line.slice(at + m.length).replace(TOKEN, "x")))
      errors.push(`${where}: {{t:${key}}} must be a whole YAML value (key: {{t:…}}, - {{t:…}}), not inside other text`);
    const v = texts.get(key);
    if (v === undefined) { errors.push(`${where}: ${key} isn't in ${dictDir}/${lang}.json`); return m; }
    if (isPlural(v)) { errors.push(`${where}: ${key} is a plural, which a YAML file can't choose from`); return m; }
    return JSON.stringify(v);
  }).replaceAll("{{lang}}", lang).replaceAll("{{file}}", file));
  return { text: errors.length ? null : `${header(template, lang, dictDir)}\n${lines.join("\n")}`, errors };
}

/** Home Assistant's Jinja in a text ({{ … }}, {% … %}), sorted: a translation must keep it as it is. */
export const jinja = (s) => [...String(s).matchAll(/\{\{[\s\S]*?\}\}|\{%[\s\S]*?%\}/g)].map((m) => m[0]).sort();

/** The keys of `flat[lang]` whose Jinja differs from English's. */
export function jinjaProblems(flat, dictDir) {
  const errors = [];
  const en = flat[FALLBACK];
  if (!en) return errors;
  for (const [lang, texts] of Object.entries(flat)) {
    if (lang === FALLBACK) continue;
    for (const [key, v] of texts) {
      const ref = en.get(key);
      if (typeof v !== "string" || typeof ref !== "string") continue;
      if (JSON.stringify(jinja(v)) !== JSON.stringify(jinja(ref)))
        errors.push(`${dictDir}/${lang}.json: ${key} changes Home Assistant's template code ({{ … }}, {% … %}) that ${FALLBACK} has`);
    }
  }
  return errors;
}

/** Every file the templates give: { files: [{ path, template, lang, text }], errors }. */
export function build(root, { surface = SURFACES.find((s) => s.id === "yaml"), langs = LANGS, kept = KEPT_PATHS, dir = "home-assistant" } = {}) {
  const dict = loadSurface(root, surface, langs);
  const errors = [...dict.problems, ...jinjaProblems(dict.flat, surface.dir)];
  const files = [];
  for (const template of listTemplates(root, dir)) {
    const source = readFileSync(path.join(root, template), "utf8");
    for (const lang of langs) {
      const out = outputPath(template, lang, kept);
      const r = render(source, { template, lang, file: path.posix.basename(out), texts: dict.flat[lang] || new Map(), dictDir: surface.dir });
      errors.push(...r.errors);
      if (r.text !== null) files.push({ path: out, template, lang, text: r.text });
    }
  }
  return { files, errors: [...new Set(errors)] };
}

/** The YAML files under `dir` that carry the generated header but that no template gives any more. */
export function orphans(root, files, dir = "home-assistant") {
  const expected = new Set(files.map((f) => f.path));
  const found = [];
  const walk = (rel) => {
    let entries = [];
    try { entries = readdirSync(path.join(root, rel), { withFileTypes: true }); } catch { return; }
    for (const e of entries) {
      const child = path.posix.join(rel, e.name);
      if (e.isDirectory() && !e.name.startsWith(".") && e.name !== "dist" && e.name !== "node_modules") walk(child);
      else if (e.isFile() && e.name.endsWith(".yaml") && !e.name.endsWith(TEMPLATE) && !expected.has(child)
        && readFileSync(path.join(root, child), "utf8").startsWith(HEADER)) found.push(child);
    }
  };
  walk(dir);
  return found.sort();
}

/** The generated files that differ from what is on disk (missing ones included). */
export function stale(root, files) {
  return files.filter((f) => {
    const file = path.join(root, f.path);
    return !existsSync(file) || readFileSync(file, "utf8") !== f.text;
  }).map((f) => f.path);
}

/** make ha-files (and --check): returns the exit code. */
export function main(root, args, log = console.log) {
  const checkOnly = args.includes("--check");
  const { files, errors } = build(root);
  const extra = orphans(root, files);
  for (const e of errors) log(`error: ${e}`);
  for (const f of extra) log(`error: ${f} is a generated file that no template gives any more: delete it`);
  if (errors.length || extra.length) {
    log(`ha-files: ${errors.length + extra.length} error(s)${checkOnly ? "" : ", nothing written"}`);
    return 1;
  }
  const changed = stale(root, files);
  if (checkOnly) {
    for (const f of changed) log(`error: ${f} is out of date with its template or its texts: run make ha-files`);
    log(changed.length ? `ha-files: ${changed.length} file(s) out of date` : `ha-files: ${files.length} file(s) up to date`);
    return changed.length ? 1 : 0;
  }
  for (const f of files.filter((x) => changed.includes(x.path))) writeFileSync(path.join(root, f.path), f.text);
  for (const f of changed) log(`  wrote ${f}`);
  log(`ha-files: ${files.length} file(s), ${changed.length} written`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exitCode = main(process.cwd(), process.argv.slice(2));
}
